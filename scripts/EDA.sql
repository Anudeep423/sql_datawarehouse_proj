-- find th total customers by countries
select
COUNTRY,
count(customer_key) as total_cutomers
from gold.dim_customers
group by COUNTRY order by total_cutomers DESC
-- find the total customers by gender
select
gender,
count(customer_key) as total_cutomers
from gold.dim_customers
group by gender order by total_cutomers DESC
-- find the total products by category
select
category,
count(product_key) as total_products
from gold.dim_products
group by category
order by total_products DESC
-- what is the average cost in each cat
select
category,
avg(cost) as avg_cost
from gold.dim_products
group by category
order by avg_cost DESC
--What is the total rev generated by each category
SELECT
p.category,
sum(f.sales_amount) as total_rev
from gold.fact_sales f
left join gold.dim_products p
on p.product_key = f.product_key
group by p.category ORDER BY total_rev DESC

-- What is the distribution of sold items across countries ?
SELECT
c.COUNTRY,
sum(f.quantity) as total_sold_items
from gold.fact_sales f
left join gold.dim_customers c
on c.customer_key = f.customer_key
group by c.country
order by total_sold_items  DESC

-- Which 5 products generate the highest rev ?
SELECT TOP 5
p.product_name,
sum(f.sales_amount) as total_rev
from gold.fact_sales f
left join gold.dim_products p
on p.product_key = f.product_key
group by
p.product_name
ORDER BY total_rev DESC
-- Which 5 products generate the LOWEST rev ?
SELECT TOP 5
p.product_name,
sum(f.sales_amount) as total_rev
from gold.fact_sales f
left join gold.dim_products p
on p.product_key = f.product_key
group by
p.product_name
ORDER BY total_rev ASC

